"""
Database connection and a guarded query runner.

The query runner is intentionally strict: it only ever executes SELECT
statements. This matters a lot in this project because SQL is being
generated by an LLM from free-text user input — we never want a model
(or a user typing something malicious) to be able to write, update,
or delete data through this app.
"""

import os

import pandas as pd
from dotenv import load_dotenv
from sqlalchemy import create_engine, text

load_dotenv()

FORBIDDEN_KEYWORDS = [
    "INSERT", "UPDATE", "DELETE", "DROP", "ALTER",
    "TRUNCATE", "GRANT", "REVOKE", "CREATE", "EXEC",
]


def get_engine():
    db_url = os.getenv("DATABASE_URL")
    if not db_url:
        raise EnvironmentError(
            "DATABASE_URL is not set. Copy .env.example to .env and fill it in."
        )
    return create_engine(db_url)


def run_readonly_query(sql: str) -> pd.DataFrame:
    """Run a SELECT-only query and return the results as a DataFrame.

    Raises ValueError if the query is not a single read-only SELECT.
    """
    cleaned = sql.strip().rstrip(";")

    if not cleaned.upper().startswith("SELECT"):
        raise ValueError("Only SELECT queries are allowed.")

    if any(keyword in cleaned.upper() for keyword in FORBIDDEN_KEYWORDS):
        raise ValueError("Query contains a forbidden keyword and was blocked.")

    if ";" in cleaned:
        # Blocks stacked queries like "SELECT ...; DROP TABLE ..."
        raise ValueError("Multiple statements are not allowed.")

    engine = get_engine()
    with engine.connect() as conn:
        return pd.read_sql(text(cleaned), conn)
